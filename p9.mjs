await new Promise(r=>setTimeout(r,3200));
console.log('Delivered?', /Delivered to/.test(app.text()));
console.log('completed', app.window.M.s.completed.map(c=>({t:c.taskId,total:c.total,collected:c.collected,method:c.method,fee:c.fee})));
console.log('BTN', JSON.stringify(labels(app).slice(15)));
console.log('next stop:', clickBtn(app, /Next stop/)); await app.settle();
console.log('STATE', state(app).stack.map(s=>s.name), state(app).tab);
console.log('home shows completed?', /Completed1/.test(app.text().replace(/\s+/g,'')));
console.log('ERR', app.errors);
app.close();
