import { bootDriver, labels, clickSel, state, onDuty, scanAll, btn, clickBtn } from './test/_drive.mjs';
const app = await bootDriver();
await onDuty(app);
clickSel(app, '[data-tour="stop"]', 0); await app.settle();
await scanAll(app);
clickBtn(app, /^Close out/); await app.settle();
clickBtn(app, /^Scan customer ID/); await app.settle();
[...app.document.querySelectorAll('button')].find(b=>!(b.textContent||'').trim() && /width: 70px/.test(b.getAttribute('style')||'')).dispatchEvent(new app.window.MouseEvent('click',{bubbles:true}));
await app.settle();
clickBtn(app, /Save to profile/); await app.settle();
clickBtn(app, /^EXPECTEDCard$/); await app.settle();
console.log('charge:', clickBtn(app, /^Charge card/)); await app.settle();
await new Promise(r=>setTimeout(r,1600));
console.log('terminal text:', /Follow the prompts/.test(app.text()));
